function parse(): EmojiItem[] {
  const items: EmojiItem[] = []
  for (const category of EMOJI_CATEGORIES) {
    for (const line of RAW[category]) {
      const space = line.indexOf(' ')
      const semi = line.indexOf(';')
      items.push({
        char: line.slice(0, space),
        name: line.slice(space + 1, semi).trim(),
        keywords: line.slice(semi + 1).trim(),
        category,
      })
    }
  }
  return items
}

export const EMOJIS: EmojiItem[] = parse()

/** Matches every word of the query against the name and keywords (prefix match). Name hits rank first. */
export function searchEmojis(query: string, list: EmojiItem[] = EMOJIS): EmojiItem[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean)
  if (!words.length) return list
  const scored: { e: EmojiItem; score: number }[] = []
  for (const e of list) {
    const nameWords = e.name.toLowerCase().split(/\s+/)
    const kwWords = e.keywords.toLowerCase().split(/\s+/)
    let score = 0
    let ok = true
    for (const w of words) {
      if (e.char === w) score += 5
      else if (nameWords.includes(w)) score += 4
      else if (nameWords.some((n) => n.startsWith(w))) score += 3
      else if (kwWords.includes(w)) score += 2
      else if (kwWords.some((k) => k.startsWith(w))) score += 1
      else {
        ok = false
        break
      }
    }
    if (ok) scored.push({ e, score: e.name.toLowerCase() === words.join(' ') ? score + 6 : score })
  }
  return scored.sort((a, b) => b.score - a.score).map((s) => s.e)
}
